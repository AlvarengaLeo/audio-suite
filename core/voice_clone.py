"""
voice_clone.py - Voice cloning on CPU (OpenVoice tone-color, isolated venv)

Architecture (so the cloning stack can't break the main app):
  - The base voice is generated by the main app's **Kokoro** TTS (Spanish,
    already installed, Gradio-6 compatible).
  - The reference speaker's **timbre** is then transferred onto that base audio
    by OpenVoice's ToneColorConverter, which runs in a **separate venv**
    (/home/user/clone-venv) via a subprocess (core/clone_infer.py) — OpenVoice's
    ancient pinned deps (gradio 3.48, numpy 1.22...) stay isolated there.

HONEST SCOPE: good speaker similarity (clearly recognizable), NOT identical nor
SOTA-API quality. Longer + cleaner reference (30-60s) improves it.

`is_clone_available()` is True only on the Space (where the venv + Kokoro
exist); locally it returns False and the UI shows a notice.
"""

import os
import subprocess
import tempfile
import logging

logger = logging.getLogger(__name__)

# Per-request limits
MIN_REF_SECONDS = 5
MAX_TEXT_CHARS = 1000

# Isolated clone venv + bridge script (created in the Dockerfile).
_VENV_PY = "/home/user/clone-venv/bin/python"
_BRIDGE = os.path.join(os.path.dirname(__file__), "clone_infer.py")

# Spanish base voice from Kokoro (display key in core.tts.KOKORO_VOICES).
_BASE_VOICE = os.environ.get("CLONE_BASE_VOICE", "🇪🇸 Dora (ES - Femenina)")


def is_clone_available() -> bool:
    """True only where the isolated clone venv and the bridge both exist."""
    return os.path.isfile(_VENV_PY) and os.path.isfile(_BRIDGE)


def _ref_duration_seconds(path: str) -> float:
    try:
        import soundfile as sf
        info = sf.info(path)
        return info.frames / float(info.samplerate or 1)
    except Exception:
        return 0.0


def _new_tempfile(suffix: str) -> str:
    f = tempfile.NamedTemporaryFile(suffix=suffix, delete=False,
                                    dir=tempfile.gettempdir())
    path = f.name
    f.close()
    return path


def clone_voice(reference_path: str, text: str,
                lang: str = "ES", denoise: bool = True) -> str:
    """
    Make the voice in `reference_path` say `text`.

    Returns path to the generated WAV. Raises ValueError on bad input.
    """
    if not reference_path or not os.path.isfile(reference_path):
        raise ValueError("Sube un audio de referencia para clonar la voz.")
    if not text or not text.strip():
        raise ValueError("Escribe el texto que dirá la voz clonada.")
    text = text.strip()
    if len(text) > MAX_TEXT_CHARS:
        raise ValueError(
            f"Texto demasiado largo ({len(text)} caracteres). "
            f"El máximo para clonación es {MAX_TEXT_CHARS:,}."
        )
    if not is_clone_available():
        raise ValueError("El motor de clonación no está disponible en este entorno.")

    # 1) Base voice in Spanish via Kokoro (main environment).
    from core.tts import _synth_kokoro, is_kokoro_available, KOKORO_VOICES
    if not is_kokoro_available():
        raise ValueError("La voz base (Kokoro) no está disponible.")
    base_voice = _BASE_VOICE if _BASE_VOICE in KOKORO_VOICES else next(iter(KOKORO_VOICES))
    base_wav = _synth_kokoro(text, base_voice, "Normal")

    # 2) Normalize the reference (and optionally denoise it for similarity).
    from core.converter import convert_to_working_format
    ref_wav = convert_to_working_format(reference_path)

    dur = _ref_duration_seconds(ref_wav)
    if dur and dur < MIN_REF_SECONDS:
        raise ValueError(
            f"La referencia es muy corta ({dur:.0f}s). Sube al menos "
            f"{MIN_REF_SECONDS}s (idealmente 30-60s) de voz limpia."
        )
    if denoise:
        try:
            from core.enhancer import enhance_with_ai, is_model_available
            if is_model_available():
                ref_wav = enhance_with_ai(ref_wav, strength="balanced",
                                          engine="DeepFilterNet")
        except Exception as e:
            logger.warning(f"Reference denoise skipped: {e}")

    # 3) Transfer the reference timbre onto the base audio (isolated venv).
    out_path = _new_tempfile("_clone.wav")
    proc = subprocess.run(
        [_VENV_PY, _BRIDGE, base_wav, ref_wav, out_path],
        capture_output=True, text=True, timeout=600,
    )
    if proc.returncode != 0 or not os.path.exists(out_path) \
            or os.path.getsize(out_path) == 0:
        logger.error(f"clone_infer failed (rc={proc.returncode}): "
                     f"{proc.stderr[-600:]}")
        raise RuntimeError("La clonación falló al procesar el audio.")

    return out_path
